     * Run the database seeds.
     *
     * create を使うため、再実行時に重複しないよう既存データがあれば何もしない。
     */
    public function run(): void
    {
        if (Review::exists()) {
            return;
        }

        $users = User::orderBy('id')->get();
        $books = Book::orderBy('id')->get();

        foreach (self::REVIEWS as $bookIndex => $reviews) {
            foreach ($reviews as $reviewIndex => [$rating, $comment]) {
                Review::create([
                    'user_id' => $users[($bookIndex + $reviewIndex) % $users->count()]->id,
                    'book_id' => $books[$bookIndex]->id,
                    'rating' => $rating,
                    'comment' => $comment,
                ]);
            }
        }
